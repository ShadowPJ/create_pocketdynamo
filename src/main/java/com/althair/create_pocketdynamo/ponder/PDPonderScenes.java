package com.althair.create_pocketdynamo.ponder;

import com.simibubi.create.AllItems;
import com.simibubi.create.foundation.ponder.CreateSceneBuilder;

import net.createmod.catnip.math.Pointing;
import net.createmod.ponder.api.PonderPalette;
import net.createmod.ponder.api.scene.SceneBuilder;
import net.createmod.ponder.api.scene.SceneBuildingUtil;
import net.createmod.ponder.api.scene.Selection;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.phys.Vec3;

/**
 * Ponder storyboards. Structures live in {@code assets/create_pocketdynamo/ponder/}, generated by
 * {@code tools/PonderStructureGen.java}; coordinates below refer to that layout (layer 0 is the base plate).
 * <p>
 * A Ponder world does not run server logic, so these scenes illustrate rather than simulate: rotation is driven with
 * {@code setKineticSpeed}, never by the real battery.
 */
public class PDPonderScenes {

	/** Scene "portable_motor/basics": what the motor is, how to set its speed, and how to carry it. */
	public static void motorBasics(SceneBuilder builder, SceneBuildingUtil util) {
		CreateSceneBuilder scene = new CreateSceneBuilder(builder);
		scene.title("portable_motor_basics", "Portable Motors");
		scene.configureBasePlate(0, 0, 5);
		scene.world().showSection(util.select().layer(0), Direction.UP);

		BlockPos motor = util.grid().at(3, 1, 2);
		Selection motorOnly = util.select().position(motor);
		Selection line = util.select().fromTo(1, 1, 2, 3, 1, 2);

		for (int i = 0; i < 3; i++) {
			scene.idle(5);
			scene.world().showSection(util.select().position(1 + i, 1, 2), Direction.DOWN);
		}
		scene.idle(10);

		scene.overlay().showText(70)
			.text("Portable Motors turn Forge Energy stored in their battery into Rotational Force")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(80);

		scene.world().setKineticSpeed(line, 16);
		scene.effects().rotationSpeedIndicator(motor);
		scene.overlay().showText(60)
			.text("While charged, they work as a source of Rotational Force anywhere")
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(70);

		Vec3 valuePanel = util.vector().blockSurface(motor, Direction.NORTH).add(1 / 16f, 0, 3 / 16f);
		scene.overlay().showFilterSlotInput(valuePanel, Direction.NORTH, 80);
		scene.overlay().showControls(valuePanel, Pointing.DOWN, 60).rightClick();
		scene.idle(20);
		scene.overlay().showText(70)
			.text("The speed and its direction are selected on the value panel. Better motors allow higher speeds")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(valuePanel);
		scene.idle(60);
		scene.world().setKineticSpeed(line, 48);
		scene.effects().rotationSpeedIndicator(motor);
		scene.idle(30);

		scene.overlay().showText(80)
			.text("Spinning faster costs more energy, even with nothing connected. Goggles show the battery and the drain")
			.attachKeyFrame()
			.colored(PonderPalette.RED)
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(90);

		scene.world().setKineticSpeed(line, 16);
		scene.overlay().showControls(util.vector().topOf(motor), Pointing.DOWN, 70)
			.rightClick()
			.withItem(AllItems.WRENCH.asStack())
			.whileSneaking();
		scene.overlay().showText(80)
			.text("Sneak and use a Wrench to pick it up. Its charge and selected speed are kept in the item")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(90);

		scene.world().hideSection(motorOnly, Direction.UP);
		scene.idle(25);
		scene.world().showSection(motorOnly, Direction.DOWN);
		scene.idle(15);
		scene.overlay().showText(60)
			.text("Place it somewhere else and it carries on with the same charge")
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(70);
	}

	/** Scene "portable_motor/charging": how the battery is filled and what happens when it empties. */
	public static void motorCharging(SceneBuilder builder, SceneBuildingUtil util) {
		CreateSceneBuilder scene = new CreateSceneBuilder(builder);
		scene.title("portable_motor_charging", "Charging the Battery");
		scene.configureBasePlate(0, 0, 5);
		scene.world().showSection(util.select().layer(0), Direction.UP);

		BlockPos motor = util.grid().at(2, 1, 2);
		BlockPos panel = util.grid().at(1, 1, 2);
		Selection motorLine = util.select().fromTo(2, 1, 2, 4, 1, 2);

		scene.idle(5);
		scene.world().showSection(motorLine, Direction.DOWN);
		scene.idle(15);

		scene.overlay().showText(70)
			.text("The battery is filled with Forge Energy from any block placed next to the motor")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(80);

		scene.world().showSection(util.select().position(panel), Direction.DOWN);
		scene.idle(15);
		scene.overlay().showOutline(PonderPalette.GREEN, "panel", util.select().position(panel), 60);
		scene.overlay().showText(70)
			.text("A Solar Panel pushes the energy it generates straight into an adjacent battery")
			.attachKeyFrame()
			.colored(PonderPalette.GREEN)
			.placeNearTarget()
			.pointAt(util.vector().topOf(panel));
		scene.idle(30);
		scene.effects().indicateSuccess(motor);
		scene.world().setKineticSpeed(motorLine, 16);
		scene.effects().rotationSpeedIndicator(motor);
		scene.idle(50);

		scene.world().setKineticSpeed(motorLine, 0);
		scene.overlay().showText(80)
			.text("When the battery runs out the motor stops. It starts again by itself as soon as it has charge")
			.attachKeyFrame()
			.colored(PonderPalette.RED)
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(90);

		scene.world().setKineticSpeed(motorLine, 16);
		scene.effects().rotationSpeedIndicator(motor);
		scene.overlay().showText(70)
			.text("Energy Cables can bring power from panels that are further away")
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(80);
	}

	/** Scene "solar_panel/sunlight": panel tiers, sky and weather requirements, and cables. */
	public static void solarSunlight(SceneBuilder builder, SceneBuildingUtil util) {
		CreateSceneBuilder scene = new CreateSceneBuilder(builder);
		scene.title("solar_panel_sunlight", "Solar Panels and Cables");
		scene.configureBasePlate(0, 0, 5);
		scene.world().showSection(util.select().layer(0), Direction.UP);

		Selection panels = util.select().fromTo(1, 1, 1, 3, 1, 1);
		Selection cables = util.select().fromTo(1, 1, 2, 3, 1, 2);
		Selection motorLine = util.select().fromTo(4, 1, 2, 4, 1, 4);
		BlockPos motor = util.grid().at(4, 1, 2);

		scene.idle(5);
		scene.world().showSection(panels, Direction.DOWN);
		scene.idle(15);

		scene.overlay().showText(70)
			.text("Solar Panels generate Forge Energy from sunlight")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(util.vector().topOf(2, 1, 1));
		scene.idle(80);

		scene.overlay().showText(80)
			.text("They need an open sky above them. Night and rain greatly reduce their output")
			.attachKeyFrame()
			.colored(PonderPalette.RED)
			.placeNearTarget()
			.pointAt(util.vector().topOf(2, 1, 1));
		scene.idle(90);

		scene.overlay().showOutline(PonderPalette.WHITE, "copper", util.select().position(1, 1, 1), 40);
		scene.overlay().showOutline(PonderPalette.WHITE, "brass", util.select().position(2, 1, 1), 40);
		scene.overlay().showOutline(PonderPalette.WHITE, "diamond", util.select().position(3, 1, 1), 40);
		scene.overlay().showText(80)
			.text("Copper, Brass and Diamond panels generate progressively more energy")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(util.vector().topOf(3, 1, 1));
		scene.idle(90);

		scene.world().showSection(cables, Direction.DOWN);
		scene.idle(15);
		scene.overlay().showText(80)
			.text("Panels push their energy into adjacent Energy Cables. Cables connect to each other and to anything that stores energy")
			.attachKeyFrame()
			.placeNearTarget()
			.pointAt(util.vector().topOf(2, 1, 2));
		scene.idle(90);

		scene.world().showSection(motorLine, Direction.DOWN);
		scene.idle(20);
		scene.effects().indicateSuccess(motor);
		scene.world().setKineticSpeed(motorLine, 16);
		scene.effects().rotationSpeedIndicator(motor);
		scene.overlay().showText(80)
			.text("This way a motor can be charged from a field of panels placed away from it")
			.placeNearTarget()
			.pointAt(util.vector().topOf(motor));
		scene.idle(90);
	}
}
